// Render / refresh HANDOFF.md. Human/agent-written sections are preserved on refresh;
// only frontmatter + the baton:auto block are regenerated.
import fs from 'node:fs';
import path from 'node:path';
import { p, VERSION } from './paths.js';
import { redact } from './redact.js';
import { clip } from './transcript.js';

export const AUTO_START = '<!-- baton:auto:start';
export const AUTO_END = '<!-- baton:auto:end -->';
const TODO = '- _(to fill)_';

export function fmtQuota(rl) {
  if (!rl) return 'unknown';
  const parts = [];
  if (rl.five_hour) parts.push(`5h ${Math.round(rl.five_hour.used_percentage)}%`);
  if (rl.seven_day) parts.push(`7d ${Math.round(rl.seven_day.used_percentage)}%`);
  return parts.join(', ') || 'unknown';
}

export function gitBlock(g) {
  if (!g || !g.isRepo) return '_Not a git repository — no git context._';
  const fence = (s) => '```text\n' + (s && s.trim() ? s.trim() : '(empty)') + '\n```';
  return [
    `Branch: \`${g.branch || '?'}\``,
    '',
    '**git status**',
    fence(g.status),
    '',
    '**git diff HEAD --stat**',
    fence(g.diffStat),
    '',
    '**last 5 commits**',
    fence(g.log),
  ].join('\n');
}

function bullets(list) {
  return list && list.length ? list.map((x) => `- \`${x}\``).join('\n') : TODO;
}

export function renderHandoff(ctx) {
  const tpl = fs.readFileSync(p.template(), 'utf8');
  const t = ctx.transcript || {};
  const goal = ctx.goal
    || (t.firstUser ? `${clip(t.firstUser, 500)}\n\n_(auto-extracted from the first prompt — please verify)_` : TODO);
  const done = t.lastAssistant ? `- Latest agent note (auto, verify):\n\n> ${clip(t.lastAssistant, 800).replace(/\n/g, '\n> ')}` : TODO;
  const next = t.lastUser && t.lastUser !== t.firstUser ? `- Last request (auto, verify): ${clip(t.lastUser, 400).replace(/\n/g, ' ')}` : TODO;
  const files = [...new Set([...(ctx.git?.files || []), ...(t.files || []).map((f) => (ctx.git?.root ? path.relative(ctx.git.root, f) : f))])]
    .filter((f) => f && !f.startsWith('..'));
  const vals = {
    baton_version: VERSION,
    from: ctx.from || 'claude',
    to: ctx.to || 'codex',
    created_at: new Date().toISOString(),
    quota_at: fmtQuota(ctx.rateLimits),
    status: ctx.status || 'skeleton',
    goal,
    done,
    decisions: TODO,
    rejected: TODO,
    files: bullets(files),
    next,
    open_questions: TODO,
    git_context: gitBlock(ctx.git),
  };
  let out = tpl.replace(/\{\{(\w+)\}\}/g, (_, k) => (vals[k] ?? ''));
  return ctx.noRedact ? out : redact(out);
}

/** Refresh frontmatter fields + auto block of an existing HANDOFF.md, keep everything else. */
export function refreshHandoff(existing, ctx) {
  let s = existing;
  const set = (k, v) => {
    const re = new RegExp(`^(${k}:).*$`, 'm');
    s = re.test(s) ? s.replace(re, `$1 ${v}`) : s;
  };
  if (s.startsWith('---')) {
    set('baton_version', VERSION);
    if (ctx.from) set('from', ctx.from);
    if (ctx.to) set('to', ctx.to);
    set('quota_at', fmtQuota(ctx.rateLimits));
    set('updated_at', new Date().toISOString());
    if (!/^updated_at:/m.test(s)) s = s.replace(/^(created_at:.*)$/m, `$1\nupdated_at: ${new Date().toISOString()}`);
  }
  const a = s.indexOf(AUTO_START), b = s.indexOf(AUTO_END);
  const block = `${AUTO_START} — regenerated by \`baton handoff\`; edit sections above, not this block -->\n## Git context\n${gitBlock(ctx.git)}\n${AUTO_END}`;
  s = a >= 0 && b > a ? s.slice(0, a) + block + s.slice(b + AUTO_END.length) : `${s.trimEnd()}\n\n${block}\n`;
  return ctx.noRedact ? s : redact(s);
}

export function hasAutoBlock(s) {
  return s.includes(AUTO_START) && s.includes(AUTO_END);
}
